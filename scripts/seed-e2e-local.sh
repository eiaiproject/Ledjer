#!/usr/bin/env bash
# Seed the local (miniflare) D1 database with the E2E fixture user.
# Idempotent — safe to run after every fresh `wrangler d1 migrations apply --local`.
# The E2E suite (playwright local-full mode) logs in as ledjer@yopmail.com.
#
# This script seeds:
#   1. User + business name
#   2. Default chart of accounts (mirror of DEFAULT_ACCOUNTS in ledger.service.ts)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DB_DIR="$ROOT/apps/web/.wrangler/state/v3/d1/miniflare-D1DatabaseObject"
DB="$(find "$DB_DIR" -maxdepth 1 -name '*.sqlite' ! -name 'metadata.sqlite' 2>/dev/null | head -1)"

if [[ -z "$DB" ]]; then
  echo "[seed-e2e-local] WARN: no local D1 database found (run db:migrations:apply:local first)" >&2
  exit 0
fi

EMAIL='ledjer@yopmail.com'
PASSWORD='Ledjer26#'
USER_ID='91175ffd-dea8-4e5e-9c83-7e2f5b6a4c21'
BUSINESS_NAME='Ledjer E2E Test'

# Generate SQL via node (accounts + password hash) — keeps bash simple.
SQL_FILE="$(mktemp /tmp/seed-e2e-local.XXXXXX)"
node - "$EMAIL" "$PASSWORD" "$USER_ID" "$BUSINESS_NAME" > "$SQL_FILE" <<'NODE'
const crypto = require("node:crypto");
const [,, email, password, userId, businessName] = process.argv;
const now = Date.now();

// ── Password hash ───────────────────────────────────────────────
const salt = crypto.randomBytes(16);
const material = Buffer.from(`${password}\u0000`, "utf8");
const key = crypto.pbkdf2Sync(material, salt, 100_000, 32, "sha256");
const hash = `pbkdf2-sha256$100000$${salt.toString("base64")}$${key.toString("base64")}`;

// ── Account UUIDs (16 MVP default accounts) ─────────────────────
// Mirror of DEFAULT_ACCOUNTS in worker/services/ledger.service.ts.
const accounts = [
  { code: "1110", name: "Kas",                    accountClass: "asset",   accountSubtype: "cash",    accountKind: null },
  { code: "1120", name: "Bank",                   accountClass: "asset",   accountSubtype: "bank",    accountKind: null },
  { code: "1130", name: "Persediaan",             accountClass: "asset",   accountSubtype: null,       accountKind: "inventory" },
  { code: "3110", name: "Modal Pemilik",          accountClass: "equity",  accountSubtype: null,       accountKind: null },
  { code: "3120", name: "Pengambilan Pemilik",    accountClass: "equity",  accountSubtype: null,       accountKind: null },
  { code: "4110", name: "Pendapatan Usaha",       accountClass: "income",  accountSubtype: null,       accountKind: null },
  { code: "4120", name: "Pendapatan Lain",        accountClass: "income",  accountSubtype: null,       accountKind: null },
  { code: "6110", name: "Beban Gaji & Upah",      accountClass: "expense", accountSubtype: null,       accountKind: null },
  { code: "6120", name: "Beban Sewa",             accountClass: "expense", accountSubtype: null,       accountKind: null },
  { code: "6130", name: "Beban Pemasaran",        accountClass: "expense", accountSubtype: null,       accountKind: null },
  { code: "6140", name: "Beban Transportasi",     accountClass: "expense", accountSubtype: null,       accountKind: null },
  { code: "6150", name: "Beban Komunikasi & Internet", accountClass: "expense", accountSubtype: null,       accountKind: null },
  { code: "6160", name: "Beban Perlengkapan",     accountClass: "expense", accountSubtype: null,       accountKind: null },
  { code: "6170", name: "Beban Administrasi",     accountClass: "expense", accountSubtype: null,       accountKind: null },
  { code: "6180", name: "Beban Lain-lain",        accountClass: "expense", accountSubtype: null,       accountKind: null },
  { code: "6190", name: "Harga Pokok Penjualan",  accountClass: "expense", accountSubtype: null,       accountKind: "cogs" },
];

const accountLines = accounts.map(a => {
  const id = crypto.randomUUID();
  const subtype = a.accountSubtype ? `'${a.accountSubtype}'` : "NULL";
  const kind = a.accountKind ? `'${a.accountKind}'` : "NULL";
  return `INSERT OR IGNORE INTO accounts
  (id, user_id, code, name, account_class, account_subtype, account_kind, is_system, is_active, created_at, updated_at)
VALUES ('${id}', '${userId}', '${a.code}', '${a.name}', '${a.accountClass}', ${subtype}, ${kind}, 1, 1, ${now}, ${now});`;
}).join("\n");

process.stdout.write(`-- Generated by scripts/seed-e2e-local.sh
-- PBKDF2-SHA256 hash for password: ${password}

-- 1. User (also carries the book name)
INSERT OR IGNORE INTO users (id, email, password_hash, full_name, business_name, status, created_at, updated_at)
VALUES ('${userId}', '${email}', '${hash}', 'Ledjer E2E', '${businessName}', 'active', ${now}, ${now});

-- 2. Default chart of accounts (required for transaction E2E tests)
${accountLines}
`);
NODE

# Apply via sqlite3
sqlite3 "$DB" < "$SQL_FILE"
rm -f "$SQL_FILE"

echo "[seed-e2e-local] seeded $EMAIL (accounts included)"